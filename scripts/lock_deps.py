"""Regenerate the hashed runtime locks from BASE_DEPS / GPU_DEPS.

    python scripts/lock_deps.py            # rewrite installer/requirements-*.lock
    python scripts/lock_deps.py --check    # exit 1 if a lock's inputs drifted

The bootstrapper (installer/vb_bootstrap.py) installs ONLY from these files with
`uv pip install --require-hashes`, so every machine gets the same versions and
the same bytes. BASE_DEPS / GPU_DEPS stay the human-edited source of truth;
after changing them, run this script and commit the locks. The header of each
lock records the exact input requirements it was compiled from, and
tests/test_dependency_locks.py fails when they no longer match.

Target: Windows x86-64, CPython 3.11 (the bootstrapper's PYTHON_VERSION).
uv: installer/bin/uv.exe (the pinned one build_exe.ps1 fetches) if present,
else `uv` on PATH; its version is recorded in the header.
"""

from __future__ import annotations

import argparse
import importlib.util
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LOCK_DIR = REPO / "installer"
PYTHON_PLATFORM = "x86_64-pc-windows-msvc"
INPUT_PREFIX = "# input: "


def load_bootstrap():
    spec = importlib.util.spec_from_file_location("vb_bootstrap_locks", REPO / "installer" / "vb_bootstrap.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def lock_inputs(boot) -> dict[str, list[str]]:
    """Lock file name -> the requirements it is compiled from."""
    return {
        boot.LOCK_FILES["base"]: list(boot.BASE_DEPS),
        boot.LOCK_FILES["gpu"]: list(boot.BASE_DEPS) + list(boot.GPU_DEPS),
    }


def recorded_inputs(lock_text: str) -> list[str]:
    """The `# input:` lines of a lock header, in order."""
    return [line[len(INPUT_PREFIX):].strip() for line in lock_text.splitlines()
            if line.startswith(INPUT_PREFIX)]


def find_uv() -> str:
    bundled = LOCK_DIR / "bin" / "uv.exe"
    if bundled.is_file():
        return str(bundled)
    on_path = shutil.which("uv")
    if on_path:
        return on_path
    raise SystemExit("uv not found: run scripts/build_exe.ps1 once (fetches installer/bin/uv.exe) or put uv on PATH")


def compile_lock(uv: str, python_version: str, requirements: list[str]) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "requirements.in"
        src.write_text("\n".join(requirements) + "\n", encoding="utf-8")
        # Relative path + cwd: the "# via -r requirements.in" annotations stay
        # identical between runs instead of naming a random temp folder.
        out = subprocess.run(
            [uv, "pip", "compile", src.name,
             "--generate-hashes", "--no-header",
             "--python-version", python_version,
             "--python-platform", PYTHON_PLATFORM],
            capture_output=True, text=True, encoding="utf-8", cwd=tmp,
        )
    if out.returncode != 0:
        raise SystemExit(f"uv pip compile failed (exit {out.returncode}):\n{out.stderr}")
    return out.stdout


def render(uv_version: str, python_version: str, requirements: list[str], body: str) -> str:
    header = [
        "# Generated by scripts/lock_deps.py - do not edit by hand.",
        "# Regenerate after changing BASE_DEPS / GPU_DEPS in installer/vb_bootstrap.py:",
        "#     python scripts/lock_deps.py",
        f"# target: {PYTHON_PLATFORM}, Python {python_version}",
        f"# {uv_version}",
        *(f"{INPUT_PREFIX}{req}" for req in requirements),
        "",
    ]
    return "\n".join(header) + body


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only verify recorded inputs, write nothing")
    args = ap.parse_args(argv)
    boot = load_bootstrap()
    targets = lock_inputs(boot)

    if args.check:
        stale = []
        for name, reqs in targets.items():
            path = LOCK_DIR / name
            if not path.is_file() or recorded_inputs(path.read_text(encoding="utf-8")) != reqs:
                stale.append(name)
        for name in stale:
            print(f"STALE {name}: run python scripts/lock_deps.py")
        return 1 if stale else 0

    uv = find_uv()
    uv_version = subprocess.run([uv, "--version"], capture_output=True, text=True, check=True).stdout.strip()
    for name, reqs in targets.items():
        body = compile_lock(uv, boot.PYTHON_VERSION, reqs)
        (LOCK_DIR / name).write_text(render(uv_version, boot.PYTHON_VERSION, reqs, body),
                                     encoding="utf-8", newline="\n")
        print(f"wrote {LOCK_DIR / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
